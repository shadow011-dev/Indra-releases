import AppKit
import SwiftUI

/// The three tabs of Duo's clipboard page, in the order they sit; Text is the one it opens on.
enum ClipTab: String, CaseIterable, Identifiable {
    case text = "Text"
    case images = "Images"
    case links = "Links"

    var id: String { rawValue }
}

struct ClipText: Identifiable, Equatable {
    let id = UUID()
    let text: String
    /// When it was copied, and the app it was copied from (its icon), for the small line under each card.
    let date: Date
    let source: NSImage?

    /// One line for the list: line breaks and runs of spaces collapse.
    var preview: String {
        text.split(whereSeparator: { $0.isWhitespace || $0.isNewline }).joined(separator: " ")
    }
}

struct ClipLink: Identifiable, Equatable {
    let id = UUID()
    let url: URL
    let date: Date
    let source: NSImage?

    /// The part after the host, shown fainter: "/user/repo".
    var path: String {
        let value = url.path
        return value == "/" ? "" : String(value.prefix(40))
    }

    var host: String {
        let host = url.host ?? url.absoluteString
        return host.hasPrefix("www.") ? String(host.dropFirst(4)) : host
    }
}

struct ClipImage: Identifiable {
    let id = UUID()
    let data: Data
    let type: NSPasteboard.PasteboardType
    let thumbnail: NSImage
    let date: Date
    let source: NSImage?
}

/// The last 30 texts and links and 10 images copied on this Mac, for Duo's Zen space. It only watches the clipboard
/// while Duo is the chosen page, keeps everything in memory (nothing is written to disk, so it is gone when Indra
/// quits), and skips what password managers mark as secret.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()
    /// Texts and links: enough that the columns scroll. Images stay few (they are big).
    static let limit = 30
    static let imageLimit = 10
    static let maxImageBytes = 25 * 1024 * 1024
    /// v506: all kept pictures together. 10 pictures of up to 25 MB each could hold 250 MB for as long as Indra ran; the oldest
    /// go first when the total passes this (the newest picture is always kept).
    static let imageBudgetBytes = 48 * 1024 * 1024

    @Published private(set) var texts: [ClipText] = []
    @Published private(set) var links: [ClipLink] = []
    @Published private(set) var images: [ClipImage] = []
    /// The tab showing on the clipboard page. It goes back to Text each time the page opens.
    @Published var tab: ClipTab = .text

    /// How many cards the shown tab holds (the notch leaves sideways swipes to the cards once they overflow).
    var activeCount: Int {
        switch tab {
        case .text: return texts.count
        case .images: return images.count
        case .links: return links.count
        }
    }

    /// The shown tab holds more cards than fit across the page, so its row scrolls sideways.
    var overflows: Bool {
        activeCount > (tab == .images ? 5 : 4)
    }

    private var timer: Timer?
    private var lastChange = NSPasteboard.general.changeCount

    private static let skippedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]

    private init() {}

    func start() {
        guard timer == nil else { return }
        lastChange = NSPasteboard.general.changeCount
        let poll = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        poll.tolerance = 0.3   // v507: lets macOS batch this wake-up with others
        RunLoop.main.add(poll, forMode: .common)
        timer = poll
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    // MARK: - Watching

    private func poll() {
        let pasteboard = NSPasteboard.general
        guard pasteboard.changeCount != lastChange else { return }
        lastChange = pasteboard.changeCount
        let types = pasteboard.types ?? []
        guard !types.contains(where: { Self.skippedTypes.contains($0) }) else { return }

        let source = Self.sourceIcon()
        // Text first (a copied table cell also carries a picture of itself); a picture only when there is no text.
        if let raw = pasteboard.string(forType: .string) {
            let text = raw.trimmingCharacters(in: .whitespacesAndNewlines)
            if !text.isEmpty {
                if let url = Self.link(in: text) {
                    add(link: url, source: source)
                } else {
                    add(text: String(text.prefix(2000)), source: source)
                }
                return
            }
        }
        if !types.contains(.fileURL),
           let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
           // v495: the full picture is kept in memory for up to 10 entries; a huge one (a raw screenshot of several
           // displays, an uncompressed TIFF) could add hundreds of megabytes, so it is not kept.
           data.count <= Self.maxImageBytes,
           let image = NSImage(data: data) {
            let type: NSPasteboard.PasteboardType = pasteboard.data(forType: .png) != nil ? .png : .tiff
            add(image: ClipImage(data: data, type: type, thumbnail: Self.thumbnail(of: image),
                                 date: Date(), source: source))
        }
    }

    /// The icon of the app in front when something is copied (almost always the app it was copied from).
    private static func sourceIcon() -> NSImage? {
        guard let icon = NSWorkspace.shared.frontmostApplication?.icon else { return nil }
        return thumbnail(of: icon, maxSide: 32)
    }

    private static let detector = try? NSDataDetector(types: NSTextCheckingResult.CheckingType.link.rawValue)

    /// The text is a single web link and nothing else.
    private static func link(in text: String) -> URL? {
        guard !text.contains(where: { $0.isWhitespace || $0.isNewline }) else { return nil }
        let range = NSRange(location: 0, length: (text as NSString).length)
        guard let match = detector?.firstMatch(in: text, options: [], range: range),
              match.range == range, let url = match.url,
              url.scheme == "http" || url.scheme == "https" else { return nil }
        return url
    }

    private static func thumbnail(of image: NSImage, maxSide: CGFloat = 480) -> NSImage {
        let size = image.size
        guard size.width > 0, size.height > 0 else { return image }
        let scale = min(1, maxSide / max(size.width, size.height))
        let target = NSSize(width: max(1, size.width * scale), height: max(1, size.height * scale))
        let thumb = NSImage(size: target)
        thumb.lockFocus()
        image.draw(in: NSRect(origin: .zero, size: target), from: .zero, operation: .copy, fraction: 1)
        thumb.unlockFocus()
        return thumb
    }

    private func add(text: String, source: NSImage?) {
        var list = texts.filter { $0.text != text }
        list.insert(ClipText(text: text, date: Date(), source: source), at: 0)
        withAnimation(.smooth(duration: 0.25)) { texts = Array(list.prefix(Self.limit)) }
    }

    private func add(link: URL, source: NSImage?) {
        var list = links.filter { $0.url != link }
        list.insert(ClipLink(url: link, date: Date(), source: source), at: 0)
        withAnimation(.smooth(duration: 0.25)) { links = Array(list.prefix(Self.limit)) }
    }

    private func add(image: ClipImage) {
        var list = images.filter { $0.data != image.data }
        list.insert(image, at: 0)
        var kept = Array(list.prefix(Self.imageLimit))
        var total = kept.reduce(0) { $0 + $1.data.count }
        while kept.count > 1, total > Self.imageBudgetBytes, let oldest = kept.popLast() { total -= oldest.data.count }
        withAnimation(.smooth(duration: 0.25)) { images = kept }
    }

    // MARK: - Using an entry

    func copy(_ item: ClipText) {
        write { $0.setString(item.text, forType: .string) }
    }

    func copy(_ item: ClipLink) {
        write { $0.setString(item.url.absoluteString, forType: .string) }
    }

    func copy(_ item: ClipImage) {
        write { $0.setData(item.data, forType: item.type) }
    }

    func remove(_ item: ClipText) { withAnimation(.smooth(duration: 0.22)) { texts.removeAll { $0.id == item.id } } }
    func remove(_ item: ClipLink) { withAnimation(.smooth(duration: 0.22)) { links.removeAll { $0.id == item.id } } }
    func remove(_ item: ClipImage) { withAnimation(.smooth(duration: 0.22)) { images.removeAll { $0.id == item.id } } }

    func clearTexts() { withAnimation(.smooth(duration: 0.22)) { texts = [] } }
    func clearLinks() { withAnimation(.smooth(duration: 0.22)) { links = [] } }
    func clearImages() { withAnimation(.smooth(duration: 0.22)) { images = [] } }

    func clearAll() {
        withAnimation(.smooth(duration: 0.22)) {
            texts = []
            links = []
            images = []
        }
    }

    /// Puts an old entry back on the clipboard; that change is not taken for a new copy.
    private func write(_ fill: (NSPasteboard) -> Bool) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        _ = fill(pasteboard)
        lastChange = pasteboard.changeCount
    }
}
